/** 按标准名查知识卡（normalizeFish 后调用） */
export function getSpeciesCard(name: string): FishSpeciesCard | undefined {
  return SPECIES_CARDS.find((c) => c.name === name);
}

/** 判断是否为首发支持的鱼种 */
export function isSupportedFish(name: string): boolean {
  return SUPPORTED_FISH.includes(name as (typeof SUPPORTED_FISH)[number]);
}

/**
 * 把知识卡压成给模型的提示词文本块。
 * 只给「形态特征 + 鉴别要点 + 相似种区分」三段——足够模型判断和叙述，
 * 不给 advice（钓法/饵料等），那是钓点知识库的职责，不是识鱼的。
 */
export function speciesPromptBlock(): string {
  return SPECIES_CARDS.map((c, i) =>
    [
      `鱼种${i + 1}：${c.name}（别名：${c.aliases.join("/")})`,
      `  形态特征：${c.morphology}`,
      `  鉴别要点：${c.keyTraits}`,
      `  相似种区分：${c.confusionWith}`,
    ].join("\n"),
  ).join("\n\n");
}

/** 知识库运行态（与 fishingRules.knowledgeMeta 对标） */
export function speciesMeta() {
  return {
    count: SPECIES_CARDS.length,
    supportedFish: [...SUPPORTED_FISH],
    reviewStatus: SPECIES_CARDS.every((c) => c.reviewStatus === "approved")
      ? "approved"
      : ("draft" as const),
  };
}
